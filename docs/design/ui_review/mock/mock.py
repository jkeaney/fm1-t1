# ------------------------------------------------------------------------------------------------------------ measure/contrast
def measure(s, fnt="S", cell=None):
    """Advance width, ink box and cap height of s in a face; whether it fits `cell` px (advance and ink), and the
    ellipsised form cv_text_fit would draw when it does not."""
    f = font(fnt) if isinstance(fnt, str) else fnt
    adv = text_w(f, s)
    b = text_ink(f, s)
    ink_w = max(0, b[2] - b[0])
    hg = f.g[f.glyph(ord('H'))]
    r = {"font": f.name, "text": s, "advance": adv, "ink_w": ink_w, "ink_x": (b[0], b[2]) if b[2] > b[0] else None,
         "ink_y": (b[1], b[3]) if b[2] > b[0] else None, "line_h": f.h, "ascent": f.asc,
         "cap_h": hg[5], "cap_y": hg[3], "cap_h_define": f.cap_h, "cap_y_define": f.cap_y}
    if cell is not None:
        r["cell"] = cell
        r["fits"] = adv <= cell
        r["ink_fits"] = ink_w <= cell
        if adv > cell:
            d, _ = text_fit_str(f, s, cell)
            r["fit_form"] = d.replace(chr(ELLIPSIS), "…")
            r["fit_form_w"] = text_w(f, d)
    return r


def lin(v):
    v /= 255.0
    return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4


def luminance(c565):
    r, g, b = to_rgb888(c565)
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast_ratio(a565, b565):
    """WCAG 2 contrast ratio of two RGB565 colours (expanded as to_rgb888)."""
    la, lb = luminance(a565), luminance(b565)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def color(spec):
    """A theme token name (TEXT, bg ..), '0xF800' (RGB565) or '#rrggbb' -> RGB565."""
    s = str(spec)
    if s.startswith("#") and len(s) == 7:
        return rgb565(int(s[1:3], 16), int(s[3:5], 16), int(s[5:7], 16))
    if s.lower().startswith("0x"):
        return int(s, 16)
    k = s.lower().replace("t_", "")
    k = "raise_" if k == "raise" else k
    if k not in Theme.TOKENS:
        sys.exit("unknown colour %r: a token (%s), 0xRGB565 or #rrggbb" % (spec, " ".join(t.upper().rstrip("_") for t in Theme.TOKENS)))
    return getattr(ux, k)


# ------------------------------------------------------------------------------------------------------------------ renders
def _scale(img, k):
    return img.resize((img.width * k, img.height * k), Image.NEAREST)


def annotate(screen, k=4, ink=True):
    """The 4x render with a pixel grid (faint lines per pixel, firm every 10 px) and the marked zones / cells outlined and labelled
    name x,y,w,h; text ink boxes in thin cyan when ink=True."""
    base = _scale(screen.to_image(), k).convert("RGBA")
    ov = Image.new("RGBA", base.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(ov)
    try:
        fnt = ImageFont.load_default(size=10)
    except TypeError:                                                      # old Pillow
        fnt = ImageFont.load_default()
    for i in range(0, W + 1):
        a = 70 if i % 10 == 0 else 26
        d.line([(i * k, 0), (i * k, H * k)], fill=(255, 255, 255, a) if i % 10 else (255, 200, 0, a))
        d.line([(0, i * k), (W * k, i * k)], fill=(255, 255, 255, a) if i % 10 else (255, 200, 0, a))
    for i in range(0, W, 20):
        d.text((i * k + 2, 1), str(i), fill=(255, 200, 0, 230), font=fnt)
        if i:
            d.text((1, i * k + 1), str(i), fill=(255, 200, 0, 230), font=fnt)
    if ink:
        for (x0, y0, x1, y1, _t, fl) in screen.texts:
            d.rectangle([x0 * k, y0 * k, x1 * k - 1, y1 * k - 1], outline=(0, 255, 255, 150) if not fl & 3 else (255, 60, 60, 230))
    cols = [(255, 0, 255), (0, 255, 120), (255, 160, 0), (80, 160, 255)]
    for n, (name, x, y, w, h) in enumerate(screen.marks):
        c = cols[n % 4]
        d.rectangle([x * k, y * k, (x + w) * k - 1, (y + h) * k - 1], outline=c + (255,), width=2)
        lab = "%s %d,%d,%d,%d" % (name, x, y, w, h)
        tw = d.textlength(lab, font=fnt)
        ly = y * k - 13 if y * k >= 14 else y * k + 2
        lx = min(max(0, x * k + 2), W * k - tw - 3)
        d.rectangle([lx - 1, ly - 1, lx + tw + 1, ly + 11], fill=(0, 0, 0, 200))
        d.text((lx, ly), lab, fill=c + (255,), font=fnt)
    return Image.alpha_composite(base, ov).convert("RGB")


def diff_images(a, b):
    """(count, pixels [(x, y)], boxes) of the differing pixels of two same-size RGB images; boxes = 8-connected clusters."""
    if a.size != b.size:
        return None
    pa, pb = a.load(), b.load()
    pts = [(x, y) for y in range(a.height) for x in range(a.width) if pa[x, y] != pb[x, y]]
    seen, boxes, ps = set(), [], set(pts)
    for p in pts:
        if p in seen:
            continue
        st, x0, y0, x1, y1, n = [p], p[0], p[1], p[0], p[1], 0
        seen.add(p)
        while st:
            x, y = st.pop()
            n += 1
            x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    q = (x + dx, y + dy)
                    if q in ps and q not in seen:
                        seen.add(q)
                        st.append(q)
        boxes.append((x0, y0, x1 - x0 + 1, y1 - y0 + 1, n))
    return len(pts), pts, boxes


def diff_png(path_a, path_b, out=None, k=4):
    """Compares two PNGs; prints the count and the clusters; writes a 4x diff PNG (A dimmed, differing pixels red, B's value
    shown in the right half of each differing cell as green) when `out`. Returns the count (or None if the sizes differ)."""
    a, b = Image.open(path_a).convert("RGB"), Image.open(path_b).convert("RGB")
    r = diff_images(a, b)
    if r is None:
        print("size differs: %s %s vs %s %s" % (path_a, a.size, path_b, b.size))
        return None
    n, pts, boxes = r
    print("%d differing pixels (of %d)  %s  vs  %s" % (n, a.width * a.height, os.path.basename(path_a), os.path.basename(path_b)))
    for (x, y, w, h, c) in boxes[:30]:
        print("  cluster x=%d y=%d w=%d h=%d  (%d px)" % (x, y, w, h, c))
    if len(boxes) > 30:
        print("  ... %d more clusters" % (len(boxes) - 30))
    if out:
        dim = Image.blend(a, Image.new("RGB", a.size, (0, 0, 0)), 0.6)
        big = _scale(dim, k)
        d = ImageDraw.Draw(big)
        for (x, y) in pts:
            d.rectangle([x * k, y * k, x * k + k - 1, y * k + k - 1], fill=(255, 0, 40))
        for (x, y, w, h, _c) in boxes:
            d.rectangle([x * k - 2, y * k - 2, (x + w) * k + 1, (y + h) * k + 1], outline=(255, 255, 0), width=1)
        big.save(out)
    return n


def load_proposal(path):
    sys.modules.setdefault("mock", sys.modules[__name__])
    d = os.path.dirname(os.path.abspath(path))
    if d not in sys.path:
        sys.path.insert(0, d)
    spec = importlib.util.spec_from_file_location(os.path.splitext(os.path.basename(path))[0], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if not hasattr(mod, "draw"):
        sys.exit("%s defines no draw(canvas, state)" % path)
    return mod


def render_state(mod, state, palette=None):
    """Runs mod.draw(canvas, state) on a fresh Screen; returns (screen, canvas)."""
    palette_set(palette or getattr(mod, "PALETTE", "GREY"))
    sc = Screen()
    cv = Canvas(sc)
    cv.begin(W, H, ux.bg)
    warn0 = len(cv.warnings)
    mod.draw(cv, state)
    if sc.nblits == 0:
        cv.blit(0, 0)
    for w in cv.warnings[warn0:]:
        print("  warning: " + w)
    return sc, cv


def render_files(mod, out, name, palette=None, k=4):
    os.makedirs(out, exist_ok=True)
    st = getattr(mod, "STATE", {}) or {}
    scenes = st.get("scenes")
    items = [(None, st)] if not scenes else [(n, {**{a: b for a, b in st.items() if a != "scenes"}, **s}) for n, s in scenes.items()]
    paths = []
    for sn, s in items:
        base = name if sn is None else "%s_%s" % (name, sn)
        print(base)
        sc, _cv = render_state(mod, s, palette)
        img = sc.to_image()
        img.save(os.path.join(out, base + ".png"))
        _scale(img, k).save(os.path.join(out, base + "_%dx.png" % k))
        annotate(sc, k).save(os.path.join(out, base + "_grid.png"))
        paths.append(os.path.join(out, base + ".png"))
    return paths


