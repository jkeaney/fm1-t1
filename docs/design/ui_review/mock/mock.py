def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(prog="mock.py", description="FM-1 240x240 pixel-exact mockup tool")
    sp = ap.add_subparsers(dest="cmd", required=True)
    r = sp.add_parser("render", help="render a proposal (a .py exposing draw(canvas, state) and STATE) to 1x, 4x and annotated 4x PNGs")
    r.add_argument("proposal")
    r.add_argument("--out", required=True)
    r.add_argument("--palette", help="palette name (default: the module's PALETTE, else GREY)")
    r.add_argument("--scale", type=int, default=4)
    d = sp.add_parser("diff", help="diff two PNGs: count, clusters, a highlighted 4x diff PNG")
    d.add_argument("a")
    d.add_argument("b")
    d.add_argument("--out")
    m = sp.add_parser("measure", help="advance width, ink box, cap height of a string; does it fit a cell")
    m.add_argument("text")
    m.add_argument("--font", default="S", choices=["S", "M", "L"])
    m.add_argument("--cell", type=int)
    c = sp.add_parser("contrast", help="WCAG contrast ratio of two colours: tokens (TEXT BG ..), 0xRGB565 or #rrggbb")
    c.add_argument("a")
    c.add_argument("b")
    c.add_argument("--palette", default="GREY")
    p = sp.add_parser("palette", help="list the palettes, or the tokens of one")
    p.add_argument("name", nargs="?")
    a = ap.parse_args(argv)
    if a.cmd == "render":
        mod = load_proposal(a.proposal)
        render_files(mod, a.out, os.path.splitext(os.path.basename(a.proposal))[0], a.palette, a.scale)
    elif a.cmd == "diff":
        n = diff_png(a.a, a.b, a.out)
        return 1 if n is None or n else 0
    elif a.cmd == "measure":
        for k, v in measure(a.text, a.font, a.cell).items():
            print("%-12s %s" % (k, v))
    elif a.cmd == "contrast":
        palette_set(a.palette)
        ca, cb = color(a.a), color(a.b)
        ratio = contrast_ratio(ca, cb)
        print("%s 0x%04X (%s) on %s 0x%04X (%s) [%s]: %.2f:1  %s" % (
            a.a, ca, "#%02x%02x%02x" % to_rgb888(ca), a.b, cb, "#%02x%02x%02x" % to_rgb888(cb), ux.palette, ratio,
            "AAA" if ratio >= 7 else "AA" if ratio >= 4.5 else "AA-large only" if ratio >= 3 else "FAIL"))
    elif a.cmd == "palette":
        if not a.name:
            print(" ".join(p_[0] for p_ in palettes()[0]))
        else:
            palette_set(a.name)
            for t in Theme.TOKENS:
                v = getattr(ux, t)
                print("%-7s 0x%04X #%02x%02x%02x" % (t.upper().rstrip("_"), v, *to_rgb888(v)))
            print("light=%d mono=%d" % (ux.light, ux.mono))
    return 0


