def _ramp(fg, bg):
    """gfx.c ramp(): the 16 colours a glyph nibble takes over `bg` in `fg` (the dark / light coverage curve)."""
    cv = CURVE_LIGHT if ux.light else CURVE_DARK
    if fg == bg:                                                           # MONO: DIM on a RAISE well (one grey): black, recessed
        fg = ux.bg
    v = []
    for a in range(16):
        w = cv[a]
        if ux.mono:
            x = bg >> 11
            v.append(ux.gray(x + ((((fg >> 11) - x) * w + 128) >> 8)))
        else:
            out = 0
            for k in range(3):
                x = (bg >> _SH[k]) & _MK[k]
                y = (fg >> _SH[k]) & _MK[k]
                out |= (x + (((y - x) * w + 128) >> 8)) << _SH[k]
            v.append(out)
    return v


CURVE_DARK = (0, 24, 43, 62, 80, 97, 114, 130, 147, 163, 178, 194, 210, 225, 240, 255)
CURVE_LIGHT = (0, 12, 27, 42, 58, 75, 91, 109, 126, 144, 162, 180, 199, 217, 236, 255)
_rc = {}


def ramp(fg, bg):
    k = (fg, bg, ux.gen)
    if k not in _rc:
        _rc[k] = _ramp(fg, bg)
    return _rc[k]


# ----------------------------------------------------------------------------------------------------------------- canvas
class Screen:
    """The 240x240 panel: what lcd_blit writes. Also collects the marks / text boxes for the annotated render."""

    def __init__(self):
        self.px = [0] * (W * H)
        self.nblits = 0
        self.marks = []          # (name, x, y, w, h)
        self.texts = []          # (x0, y0, x1, y1, string, flags)

    def to_image(self):
        lut = {}
        buf = bytearray()
        for c in self.px:
            t = lut.get(c)
            if t is None:
                t = lut[c] = bytes(to_rgb888(c))
            buf += t
        return Image.frombytes("RGB", (W, H), bytes(buf))


class Canvas:
    """gfx.c's off-screen strip (cv_*): begin() sizes and clears it, the draw calls write RGB565, blit() sends it to the Screen."""
    MAX = 240 * 124            # CV_MAX: the firmware's strip. A bigger one is allowed here but flagged in .warnings

    def __init__(self, screen=None):
        self.screen = screen or Screen()
        self.warnings = []
        self.begin(W, H, ux.bg)

    # --- canvas
    def begin(self, w, h, bg=None):
        if w * h > Canvas.MAX:
            self.warnings.append("canvas %dx%d is over the firmware's 240x124 strip (CV_MAX); the device would clip it" % (w, h))
        self.w, self.h = w, h
        self.bg = ux.bg if bg is None else bg
        self.px = [self.bg] * (w * h)
        self.cy0, self.cy1 = 0, h
        self.texts = []
        self.marks = []
        return self

    def blit(self, x, y):
        """cv_blit: the canvas to the panel at (x, y)."""
        s = self.screen
        s.nblits += 1
        for r in range(self.h):
            if 0 <= y + r < H:
                for c in range(self.w):
                    if 0 <= x + c < W:
                        s.px[(y + r) * W + x + c] = self.px[r * self.w + c]
        s.marks += [(n, mx + x, my + y, mw, mh) for (n, mx, my, mw, mh) in self.marks]
        s.texts += [(a + x, b + y, c + x, d + y, t, f) for (a, b, c, d, t, f) in self.texts]

    def mark(self, name, x, y, w, h):
        """A labelled zone / cell for the annotated render (canvas coordinates)."""
        self.marks.append((name, x, y, w, h))

    # --- primitives
    def pset(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y * self.w + x] = c

    def rect(self, x, y, w, h, c):
        x1, y1 = min(x + w, self.w), min(y + h, self.h)
        x, y = max(x, 0), max(y, 0)
        for j in range(y, y1):
            b = j * self.w
            for i in range(x, x1):
                self.px[b + i] = c

    def frame(self, x, y, w, h, c):
        self.rect(x, y, w, 1, c)
        self.rect(x, y + h - 1, w, 1, c)
        self.rect(x, y, 1, h, c)
        self.rect(x + w - 1, y, 1, h, c)

    def rule(self, x, y, w, h):
        self.rect(x, y, w, h, ux.dim)

    def line(self, x0, y0, x1, y1, c):
        dx, sx = abs(x1 - x0), 1 if x0 < x1 else -1
        dy, sy = -abs(y1 - y0), 1 if y0 < y1 else -1
        err = dx + dy
        for _ in range(2000):
            e2 = 2 * err
            self.pset(x0, y0, c)
            if x0 == x1 and y0 == y1:
                break
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def line_t(self, x0, y0, x1, y1, c, thick):
        for t in range(thick):
            self.line(x0, y0 + t, x1, y1 + t, c)

    @staticmethod
    def rr_cov(r, i, j):
        n = 0
        for sy in range(4):
            for sx in range(4):
                dx = r * 8 - ((i * 4 + sx) * 2 + 1)
                dy = r * 8 - ((j * 4 + sy) * 2 + 1)
                n += dx * dx + dy * dy <= r * r * 64
        return n

    def rrect(self, x, y, w, h, r, c, under):
        """cv_rrect: a rounded rectangle, r <= 8, the corners anti-aliased against `under`. r < 0: rounded in every style."""
        if r < 0:
            r = -r
        elif ux.style == 1:
            r = 0
        r = min(r, w // 2, h // 2)
        if r < 1:
            self.rect(x, y, w, h, c)
            return
        self.rect(x + r, y, w - 2 * r, h, c)
        self.rect(x, y + r, r, h - 2 * r, c)
        self.rect(x + w - r, y + r, r, h - 2 * r, c)
        for j in range(r):
            for i in range(r):
                a = self.rr_cov(r, i, j)
                px = c if a >= 16 else under if a == 0 else ux.mix(under, c, a * 100 // 16)
                self.pset(x + i, y + j, px)
                self.pset(x + w - 1 - i, y + j, px)
                self.pset(x + i, y + h - 1 - j, px)
                self.pset(x + w - 1 - i, y + h - 1 - j, px)

    def _alpha(self, x, y, w, h, nib, rv):
        for gy in range(h):
            py = y + gy
            if py < self.cy0 or py >= self.cy1:
                continue
            row = py * self.w
            for gx in range(w):
                v = nib[gy * w + gx]
                px = x + gx
                if v and 0 <= px < self.w:
                    self.px[row + px] = rv[v]

    # --- text
    def text_flags(self, x, y, f, s, fg, bg, flags=0):
        if isinstance(f, str):
            f = font(f)
        pen, b = _text_run(f, s, x, y, self, ramp(fg, bg))
        if b[2] > b[0]:
            if b[0] < 0 or b[2] > self.w or b[1] < self.cy0 or b[3] > self.cy1:
                flags |= 2                                                   # cut by the canvas
            self.texts.append((b[0], b[1], b[2], b[3], s, flags))
            if flags & 2:
                self.warnings.append("text %r is cut by the canvas (ink %d,%d..%d,%d)" % (s, b[0], b[1], b[2], b[3]))
        return x + ((pen + 8) >> 4)

    def text_on(self, x, y, f, s, fg, bg):
        return self.text_flags(x, y, f, s, fg, bg, 0)

    def text(self, x, y, f, s, fg):
        """cv_text: on the canvas background (the colour begin() cleared to). Returns the pen x at the end."""
        return self.text_flags(x, y, f, s, fg, self.bg, 0)

    def text_r(self, xr, y, f, s, fg, bg):
        w = text_w(f, s)
        self.text_on(xr - w, y, f, s, fg, bg)
        return xr - w

    def text_in(self, x0, y, w, f, s, fg, bg):
        """cv_text_in: s with its INK centred across x0 .. x0 + w; y is the line top (CAP_IN to centre it up and down)."""
        if isinstance(f, str):
            f = font(f)
        return self.text_on(x0 + ink_in(f, s, w), y, f, s, fg, bg)

    def text_fit(self, x, y, f, s, fg, bg, maxw):
        """cv_text_fit: in maxw px, the end ellipsised when longer (a label or a value must fit)."""
        d, cut = text_fit_str(f, s, maxw)
        if cut:
            self.warnings.append("text %r ellipsised to %r in %d px" % (s, d.replace(chr(ELLIPSIS), "\u2026"), maxw))
        return self.text_flags(x, y, f, d, fg, bg, 1 if cut else 0)

    def free_text(self, x, y, f, s, fg, bg, maxw):
        d, cut = text_fit_str(f, s, maxw)
        return self.text_flags(x, y, f, d, fg, bg, 9 if cut else 8)

    # --- bitmaps
    def glyph1(self, x, y, art, color, under=None, flip=False):
        """A 1-bit mini glyph (a custom 5-10 px icon) from ASCII art: '#', 'X' or '@' sets a pixel; '.', ' ' and '_' leave it
        (or fill `under` when given). art = a list of rows or a newline-separated string. Returns (w, h)."""
        rows = art.strip("\n").split("\n") if isinstance(art, str) else list(art)
        rows = [r.rstrip("\r") for r in rows]
        w = max(len(r) for r in rows)
        hh = len(rows)
        if not (1 <= w <= 10 and 1 <= hh <= 10):
            self.warnings.append("glyph1 %dx%d is outside the 5-10 px icon range" % (w, hh))
        for j, r in enumerate(rows):
            r = r.ljust(w)
            if flip:
                r = r[::-1]
            for i, ch in enumerate(r):
                if ch in "#X@":
                    self.pset(x + i, y + j, color)
                elif under is not None:
                    self.pset(x + i, y + j, under)
        return w, hh

    def paste(self, src, x, y, key=None):
        """Copies another Canvas into this one at (x, y); pixels equal to `key` are skipped."""
        for j in range(src.h):
            for i in range(src.w):
                c = src.px[j * src.w + i]
                if c != key:
                    self.pset(x + i, y + j, c)


