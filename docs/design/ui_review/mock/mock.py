def _ints(body):
    return [int(t, 0) for t in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]


def _cdiv(a, b):
    """C integer division (truncates toward zero)."""
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


