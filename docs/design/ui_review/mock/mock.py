class Font:
    """An aafont_t of gfx.c. g[i << psh .. +phases-1] are a glyph's phases; advances and kerning are in 1/16 px."""

    def __init__(self, name, src):
        self.name = name

        def arr(n):
            m = re.search(r"\b%s\[[^\]]*\]\s*=\s*\{(.*?)\};" % re.escape(n), src, re.S)
            if not m:
                sys.exit("ui_fonts.h: array %s not found" % n)
            return _ints(m.group(1))
        m = re.search(r"static const aafont_t AF_%s\s*=\s*\{([^}]*)\}" % name, src)
        t = [x.strip() for x in m.group(1).split(",")]
        self.h, self.asc, self.first, self.last, self.nex, self.nk = (int(x) for x in t[:6])
        g = arr(t[6])
        self.g = [tuple(g[i:i + 6]) for i in range(0, len(g), 6)]          # off, adv, bx, by, bw, bh
        self.data = bytes(arr(t[7]))
        self.kern = dict(zip(arr(t[8]), arr(t[9])))
        self.ex = arr(t[10])
        self.psh = int(t[11])
        self.hc = arr(t[12]) if t[12] != "0" else None
        self.cap_y = int(re.search(r"#define AF_%s_CAP_Y (\d+)" % name, src).group(1))
        self.cap_h = int(re.search(r"#define AF_%s_CAP_H (\d+)" % name, src).group(1))
        self._bm = {}

    def glyph_at(self, ch):
        if self.first <= ch <= self.last:
            return ch - self.first
        if ch in self.ex:
            return self.last - self.first + 1 + self.ex.index(ch)
        return -1

    def glyph(self, ch):
        """The table index of ch at phase 0 (gfx.c glyph): not in the face -> the ellipsis as '.', else '?', else glyph 0."""
        if ord('a') <= ch <= ord('z') and self.last < ord('a'):
            ch -= 32
        k = self.glyph_at(ch)
        if k < 0 and ch == ELLIPSIS:
            k = self.glyph_at(ord('.'))
        if k < 0:
            k = self.glyph_at(ord('?'))
        if k < 0:
            k = 0
        return k << self.psh

    def fold(self, c):
        return c - 32 if ord('a') <= c <= ord('z') and self.last < ord('a') else c

    def bitmap(self, gi):
        """w*h alpha nibbles (0..15) of table entry gi, rows back to back (cv_alpha / cv_alpha_hc)."""
        if gi in self._bm:
            return self._bm[gi]
        off, _adv, _bx, _by, bw, bh = self.g[gi]
        n = bw * bh
        out = []
        if self.hc is None:                                                # two nibbles a byte, high first
            for k in range(n):
                out.append((self.data[off + (k >> 1)] >> (0 if k & 1 else 4)) & 15)
        else:                                                              # canonical Huffman, MSB first, symbol = (run-1)<<4 | value
            hc = self.hc
            pos = off * 8
            while len(out) < n:
                code = first = idx = ln = 0
                while True:
                    bit = (self.data[pos >> 3] >> (7 - (pos & 7))) & 1
                    pos += 1
                    code |= bit
                    if code - first < hc[ln]:
                        break
                    idx += hc[ln]
                    first = (first + hc[ln]) << 1
                    code <<= 1
                    ln += 1
                s = hc[15 + idx + code - first]
                out.extend([s & 15] * ((s >> 4) + 1))
            del out[n:]
        self._bm[gi] = out
        return out


_FONTS = {}


def font(name):
    """AF_S / AF_M / AF_L by letter."""
    if not _FONTS:
        src = _read_gen("ui_fonts.h")
        for n in "SML":
            _FONTS[n] = Font(n, src)
    return _FONTS[name]


AF_S, AF_M, AF_L = font('S'), font('M'), font('L')


def _codes(s):
    out = []
    for ch in s:
        o = ord(ch)
        out.append(ELLIPSIS if o == 0x2026 else o if o < 256 else ord('?'))
    return out


def text_w(f, s):
    """gfx.c text_w: the advance of s in px (kerned, rounded)."""
    if isinstance(f, str):
        f = font(f)
    pen = 0
    prev = 0
    for c in _codes(s) if isinstance(s, str) else s:
        c = f.fold(c)
        if prev:
            pen += f.kern.get((prev << 8) | c, 0)
        pen += f.g[f.glyph(c)][1]
        prev = c
    return (pen + 8) >> 4


def text_fit_str(f, s, maxw, n=48):
    """gfx.c text_fit: (the drawn string, cut). Never a smaller font: the end is ellipsised (chr(0x85)). n = the C buffer (48)."""
    if isinstance(f, str):
        f = font(f)
    d = list(s[:n - 1])
    k = len(d)
    if k == len(s) and text_w(f, "".join(d)) <= maxw:
        return "".join(d), 0
    if k + 2 > n:
        k = n - 2
    d = d[:k] + [""] * 2
    while True:
        while k and d[k - 1] == ' ':
            k -= 1
        d = d[:k] + [chr(ELLIPSIS)]
        if not k or text_w(f, "".join(d)) <= maxw:
            return "".join(d), 1
        k -= 1


def _text_run(f, s, x, y, cv, rv):
    """gfx.c text_run: places each glyph at its phase, draws it (when rv) and returns (pen, [x0, y0, x1, y1] of the ink)."""
    pen = err = 0
    x0 = y0 = 0x7FFF
    x1 = y1 = -0x7FFF
    step = 16 >> f.psh
    prev = 0
    for c in _codes(s):
        c = f.fold(c)
        if prev:
            pen += f.kern.get((prev << 8) | c, 0)
        gi = f.glyph(c)
        if f.psh and gi + 1 < len(f.g) and f.g[gi + 1][0] != f.g[gi][0]:
            pos = pen - (pen & (step - 1))
            d0 = pos - pen - err
            d1 = d0 + step
            if abs(d0) > abs(d1):
                pos += step
            gi += (pos >> (4 - f.psh)) & ((1 << f.psh) - 1)
        else:
            pos = (pen + 8) & ~15
        err = pos - pen
        off, adv, bx, by, bw, bh = f.g[gi]
        if bw:
            gx, gy = x + (pos >> 4) + bx, y + by
            if rv is not None:
                cv._alpha(gx, gy, bw, bh, f.bitmap(gi), rv)
            x0 = min(x0, gx)
            x1 = max(x1, gx + bw)
            y0 = min(y0, gy)
            y1 = max(y1, gy + bh)
        pen += adv
        prev = c
    return pen, [x0, y0, x1, y1]


def text_ink(f, s):
    """The ink box [x0, y0, x1, y1] of s drawn at (0, 0) (x1 past it; x1 <= x0: no ink)."""
    if isinstance(f, str):
        f = font(f)
    return _text_run(f, s, 0, 0, None, None)[1]


def ink_in(f, s, w):
    b = text_ink(f, s)
    return ((w - (b[2] - b[0])) >> 1) - b[0]


# ------------------------------------------------------------------------------------------------------------------ theme
def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def to_rgb888(c):
    """RGB565 -> (r, g, b) with the expansion of tests/ui_sq_test.c png_write (see the module docstring)."""
    return (((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31)


_SH = (11, 5, 0)
_MK = (31, 63, 31)


class Theme:
    """gfx.c `ux`: the stored colours + the derived ones, built by palette_set()."""
    TOKENS = ("bg", "surf", "text", "theme", "accent", "mid", "dim", "line", "sel", "tint", "ink", "rec", "raise_", "key", "lane", "grid")

    def __init__(self):
        self.style = 0
        self.gen = 0
        self.set("GREY")

    def gray(self, x5):
        return (x5 << 11) | (x5 << 6) | x5

    def mix(self, a, b, pct):
        """gfx.c ux_mix: a + (b - a) * pct / 100 per channel, rounded; GREY on the red channel so it stays gray."""
        if self.mono:
            x = a >> 11
            d = ((b >> 11) - x) * pct
            return self.gray(x + _cdiv(d + (50 if d >= 0 else -50), 100))
        out = 0
        for k in range(3):
            x = (a >> _SH[k]) & _MK[k]
            d = (((b >> _SH[k]) & _MK[k]) - x) * pct
            out |= (x + _cdiv(d + (50 if d >= 0 else -50), 100)) << _SH[k]
        return out

    @staticmethod
    def luma(c):
        return (((c >> 11) * 255 // 31) * 54 + (((c >> 5) & 63) * 255 // 63) * 183 + ((c & 31) * 255 // 31) * 19) >> 8

    def set(self, name):
        pals, defs = palettes()
        if isinstance(name, int):
            idx = name % len(pals)
        else:
            names = [p[0] for p in pals]
            if name.upper() not in names:
                sys.exit("unknown palette %r (have %s)" % (name, ", ".join(names)))
            idx = names.index(name.upper())
        _n, bg, surf, text, theme, accent = pals[idx]
        self.palette = pals[idx][0]
        self.mono = idx == defs["UI_GREY_INDEX"]
        self.bg, self.surf = bg, bg if self.style else surf
        self.text, self.theme, self.accent = text, theme, accent
        self.mid = self.mix(bg, text, defs["UI_MID_PCT"])
        self.dim = self.mix(bg, text, defs["UI_DIM_PCT"])
        self.line = self.mix(bg, text, defs["UI_LINE_PCT"])
        self.sel = self.mix(bg, theme, defs["UI_SEL_PCT"])
        self.tint = self.mix(bg, theme, defs["UI_TINT_PCT"])
        self.ink = bg
        self.raise_ = self.mix(surf, text, defs["UI_RAISE_PCT"])
        self.key = self.mix(bg, text, defs["UI_KEY_PCT"])
        self.lane = self.mix(self.surf, theme, 10)
        self.grid = self.mix(self.surf, text, 6)
        self.light = int(self.luma(bg) > 128)
        self.rec = accent if self.mono else defs["UI_REC_LIGHT"] if self.light else defs["UI_REC_DARK"]
        if idx == defs["UI_BW_INDEX"]:                                     # MONO: black and white, set not blended
            self.mid = self.sel = self.key = self.rec = text
            self.dim = self.line = self.raise_ = self.lane = defs["UI_BW_GREY"]
            self.tint = self.grid = bg
        self.gen += 1


class _Tokens:
    """T.BG, T.TEXT ...: the theme tokens, read at use."""

    def __getattr__(self, n):
        k = n.lower()
        if k == "raise":
            k = "raise_"
        if n != n.upper() or k not in Theme.TOKENS:
            raise AttributeError(n)
        return getattr(ux, k)


