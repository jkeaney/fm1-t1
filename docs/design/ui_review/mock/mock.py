"""mock.py: a pixel-exact mockup tool for the FM-1 240x240 RGB565 screen.

It is a Python port of the parts of firmware/src/gfx.c a screen is drawn with, fed by the REAL data:

  fonts      AF_S / AF_M / AF_L: the 4-bit alpha glyph tables, advances, kerning and phases parsed out of build/gen/ui_fonts.h
             (generated by tools/gen_aa_font.py from Inter Tight; the firmware's cv_alpha nibble stream for S, the Huffman stream
             cv_alpha_hc for M and L). No TTF is used: the glyph bitmaps are the ones the device blits.
  palette    UI_PALETTES + the UI_*_PCT derivation of build/gen/ui_palettes.h, derived exactly as gfx.c palette_set does (ux_mix,
             the MONO / GREY gray ramps, the light-palette text curve). Default palette GREY (index 0), which is what
             tests/ui_sq_test.c renders with (palette_set(0)).
  labels     build/gen/ui_tables.h (page cues, knob / button / key label rows), parsed by `tables()`.

Colour expansion RGB565 -> sRGB (for the PNGs): the SAME as the png_write() of tests/ui_sq_test.c that wrote build/ui_sq/*.png:
r = r5 * 255 // 31, g = g6 * 255 // 63, b = b5 * 255 // 31 (integer, rounded down). What the physical panel does with the 16 bits is
the panel's; this is the repo's reference rendering, so the mock and the shipping render share it.

Canvas API (names follow gfx.c): begin, rect, frame, pset, line, line_t, rrect, text, text_on, text_r, text_in, text_fit, free_text,
blit, plus glyph1 (1-bit ASCII-art mini glyphs), paste, mark (a labelled zone / cell for the annotated render). Colours are RGB565
ints; the theme tokens are `T.BG T.SURF T.TEXT T.THEME T.ACCENT T.MID T.DIM T.LINE T.SEL T.TINT T.INK T.REC T.RAISE T.KEY T.LANE
T.GRID` (read at use, like the firmware's ux.*).

CLI:  mock.py render PROPOSAL.py --out DIR     mock.py diff A.png B.png --out diff.png
      mock.py measure "TEXT" --font S --cell 36   mock.py contrast TEXT BG [--palette GREY]   mock.py palette [NAME]
"""
