class Tables:
    """build/gen/ui_tables.h as Python: enum ids by name, and the label rows (page cues, knob / button / key labels)."""

    def __init__(self, src):
        self.enums = {}
        for m in re.finditer(r"typedef enum \{(.*?)\} (ui_\w+_t);", src, re.S):
            names = [re.sub(r"\s*=.*", "", x).strip() for x in m.group(1).split(",") if x.strip()]
            for i, n in enumerate(names):
                self.enums[n] = i
        self.ctl_names = [n for n, _ in sorted(self.enums.items(), key=lambda kv: kv[1]) if n.startswith("UI_C_")]

        def rows(name, nfields):
            m = re.search(r"static const \w+ %s\[[^\]]*\]\s*=\s*\{(.*?)\n\};" % name, src, re.S)
            out = []
            for r in re.finditer(r"\{\s*([^{}]*?)\s*\},?\n", m.group(1)):
                f = re.findall(r'"((?:[^"\\]|\\.)*)"|([A-Za-z_]\w*)', r.group(1))
                out.append([(a.replace('\\"', '"').replace("\\\\", "\\") if a or not b else b) for a, b in f])
            return out
        E = self.enums
        self.page_rows = [(E[r[0]], r[1], r[2]) for r in rows("ui_page_rows", 3)]
        self.button_rows = [(E[r[0]], E[r[1]], E[r[2]], r[3]) for r in rows("ui_button_rows", 4)]
        self.knob_rows = [(E[r[0]], E[r[1]], E[r[2]], r[3]) for r in rows("ui_knob_rows", 4)]
        self.key_rows = [(E[r[0]], E[r[1]], E[r[2]], r[3]) for r in rows("ui_key_rows", 4)]
        self.page_names = [n[len("UI_PG_"):] for n in sorted((n for n in E if n.startswith("UI_PG_") and n != "UI_PG_COUNT"), key=E.get)]

    def knob_label(self, page, ctx, knob):
        """ui_sq.c uisq_knob_label: the exact algorithm's row first, else the any-algorithm row (the last one)."""
        anyl = ""
        for p, c, k, lab in self.knob_rows:
            if p != page or k != knob:
                continue
            if c == ctx:
                return lab
            if c == self.enums["UI_CTX_ANY"]:
                anyl = lab
        return anyl

    def btn_label(self, page, ctl, mode):
        for p, c, m, lab in self.button_rows:
            if p == page and c == ctl and m == mode:
                return lab
        return ""

    def key_label(self, page, ctl, gest):
        for p, c, g, lab in self.key_rows:
            if p == page and c == ctl and g == gest:
                return lab
        return ""

    def page_cue(self, page):
        for i, _k, cue in self.page_rows:
            if i == page:
                return cue
        return ""


