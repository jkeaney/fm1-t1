/* probe.c: dumps the sequencer state tests/ui_sq_test.c had when it wrote build/ui_sq/perf.png, perf_row2.png, perf_playing.png and
 * perf_snake_mute.png, as JSON (fixtures/perf_fixtures.json), so the Python mock draws from the SAME inputs. The state changes below
 * are copied, in order, from the "render every page" section of the test; the test itself is included with its main renamed (it supplies
 * the host side of gfx.c and the real sq_core / sq_chan / ALGOS). Build and run: fixtures/gen_fixtures.sh (from the repo root).
 * Not part of the firmware or its tests. */
#define main ui_sq_test_main
#include "../../../../../tests/ui_sq_test.c"
#undef main

static void dump_scn(const char *name, int first)
{   const uint8_t ch = uisq_sel; UisqStep L[SQ_PAGE];
    uisq_lane_read(L, ch, uisq_vpage);
    printf("%s  \"%s\": {\n    \"page\": %u, \"sel\": %u, \"vpage\": %u, \"row\": %u, \"playing\": %u, \"bpm\": %u, \"follow\": %u, \"preset\": %u, \"preset_pend\": %u,\n",
           first ? "" : ",\n", name, uisq_page, uisq_sel, uisq_vpage, uisq_row, (unsigned)sq_playing, (unsigned)sq_bpm, (unsigned)sq_follow, uisq_preset, uisq_preset_pend);
    printf("    \"playhead\": %u, \"hot\": [", uisq_playhead(ch));
    for (int k = 0; k < 4; k++) printf("%s%d", k ? ", " : "", uisq_now < uisq_hot_until[k]);
    printf("],\n    \"channels\": [\n");
    for (int c = 0; c < SQ_NCH; c++)
        printf("      {\"algo\": %u, \"midi_ch\": %u, \"muted\": %u, \"len\": %u, \"pg_used\": %u, \"snd0\": %u, \"p\": %u}%s\n", sq_ch[c].algo, sq_ch[c].midi_ch,
               sq_ch[c].muted, sq_ch[c].len, sq_ch[c].pg_used, (unsigned)(sq_rt[c].snd[0] != 0), (unsigned)sq_rt[c].p, c < SQ_NCH - 1 ? "," : "");
    printf("    ],\n    \"morph\": [");
    for (int i = 0; i < SQ_NMORPH; i++) printf("%s%u", i ? ", " : "", sq_ch[ch].st[sq_ch[ch].algo % SQ_NALGO].morph[i]);
    printf("],\n    \"lane\": [\n");
    for (int n = 0; n < SQ_PAGE; n++)
        printf("      {\"on\": %u, \"vel\": %u, \"ed\": %u, \"acc\": %u, \"slide\": %u, \"rep\": %u}%s\n", L[n].on, L[n].vel, L[n].ed, L[n].acc, L[n].slide, L[n].rep, n < SQ_PAGE - 1 ? "," : "");
    printf("    ]\n  }"); }

int main(void)
{   crc_init(); palette_set(0);                      /* the test's palette: index 0 = GREY (mono) */
    sq_boot(); fm1_ms = 1000;
    sq_ch[0].len = 20; sq_ch[0].pg_used = 3; sq_ch[1].muted = 0; sq_ch[2].midi_ch = SQ_MIDI_OFF;
    sq_ch[0].ed[2].vel = 90; sq_ch[0].ed[4].fl = 1; sq_ch[0].ed[7].fl = (uint8_t)(1 | (1 << 2)); sq_ch[0].ed[9].gr = 0x20;
    sq_rebuild(0);
    uisq_sel = 0; fresh();
    printf("{\n  \"_note\": \"generated by fixtures/probe.c from tests/ui_sq_test.c state; palette_set(0)\",\n  \"algos\": [\n");
    for (int a = 0; a < SQ_NALGO; a++) {
        printf("    {\"name\": \"%s\", \"sub\": [", ALGOS[a].name);
        for (int i = 0; i < 5; i++) printf("%s\"%s\"", i ? ", " : "", ALGOS[a].sub[i]);
        printf("], \"layer_n\": [");
        for (int i = 0; i < 5; i++) printf("%s%u", i ? ", " : "", ALGOS[a].layer[i].n);
        printf("], \"knob_morph\": [");
        for (int i = 0; i < 8; i++) printf("%s%u", i ? ", " : "", ALGOS[a].knob_morph[i]);
        printf("]}%s\n", a < SQ_NALGO - 1 ? "," : ""); }
    printf("  ],\n  \"scenes\": {\n");
    dump_scn("perf", 1);
    uisq_edit_step = 20;                             /* (the page loop leaves it so; only NOTE_EDIT reads it) */
    uisq_page = UI_PG_PERF; uisq_row = 1; fresh(); dump_scn("perf_row2", 0); uisq_row = 0;
    sq_playing = 1; sq_rt[0].p = 6; sq_rt[0].snd[0] = 1; fresh(); dump_scn("perf_playing", 0); sq_playing = 0; sq_rt[0].snd[0] = 0;
    sq_ch[1].muted = 1; sq_ch[2].midi_ch = 1; sq_set_algo(0, 2); fresh(); dump_scn("perf_snake_mute", 0);
    printf("\n  }\n}\n");
    return 0; }
