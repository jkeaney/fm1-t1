"""icons_v7.py: the icon set, reviewed (round 4). Rule: a DIE FRAME means 're-roll'; what is inside the die names the
layer it re-rolls. Every other button has its own silhouette, none framed. 13x13 unless noted."""

DIE = [".###########.", "#...........#"] + ["#...........#"] * 9 + ["#...........#", ".###########."]


def die(inner):
    """inner: 9 rows of 9 chars placed at (2,2) inside the die frame"""
    rows = [list(r) for r in DIE]
    for j, r in enumerate(inner.strip("\n").split("\n")):
        for i, c in enumerate(r):
            if c == "#":
                rows[2 + j][2 + i] = "#"
    return "\n".join("".join(r) for r in rows)


