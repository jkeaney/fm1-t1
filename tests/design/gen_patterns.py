"""P2-017: the generator of the PATTERNS const table. Reads docs/design/algorithms/patterns/patterns.tsv through patterns_proto.load()
(the one parser) and writes patterns_data.h next to it, in the binary format of patterns/SPEC.md 3.3:
  PAT_STEP[]: 2 B per step, rest = 0x0000.  low byte: bit7 ON, bit6 TIE, bits0-5 pitch (0..48 SEMI, 0..14 DEG);
                                              high byte: bit0 ACC, bit1 SLD, bit2 CT, bits3-4 RANK, bits5-6 GATE (0 short, 1 normal, 2 long), bit7 OPT.
  PAT_HEAD[]: first (index into PAT_STEP), len, flags (bit0 DEG, bit1 F idiom).   id = 20 * category + number - 1.
  python3 tests/design/gen_patterns.py            rewrite patterns_data.h
  python3 tests/design/gen_patterns.py --check    exit 1 if patterns_data.h differs from what the tsv gives (run_protos.sh runs this)
No pattern name, category name or song title is written into the table: names live in the P5-008 name table, so the title grep of
patterns_proto.py --check has nothing to find in the generated data."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import patterns_proto as pp

OUT = os.path.join(pp.PD, "patterns_data.h")


def text():
    lib = pp.load()
    heads, words = [], []
    for p in lib:
        heads.append((len(words), p["len"], (1 if p["mode"] == "DEG" else 0) | (2 if p["src"] == "F" else 0)))
        for st in p["steps"]:
            if st is None:
                words.append(0)
                continue
            on = 0 if st["opt"] else 1
            b0 = (on << 7) | ((1 if st["tie"] else 0) << 6) | st["p"]
            b1 = (1 if st["acc"] else 0) | ((1 if st["sld"] else 0) << 1) | ((1 if st["ct"] else 0) << 2) | (st["rank"] << 3) | (st["gate"] << 5) | ((1 if st["opt"] else 0) << 7)
            assert 0 <= st["p"] <= 48 and st["rank"] <= 3
            words.append(b0 | (b1 << 8))
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* patterns_data.h: GENERATED by tests/design/gen_patterns.py from patterns.tsv. Do not edit; run_protos.sh fails if it is stale.",
         " * %d patterns, %d steps: %d B of steps + %d B of heads = %d B of flash, no RAM (PATTERNS SPEC 3.3, 3.4). */" % (len(heads), len(words), 2 * len(words), 4 * len(heads), 2 * len(words) + 4 * len(heads)),
         "#ifndef PATTERNS_DATA_H", "#define PATTERNS_DATA_H", "",
         "#define PAT_N %d" % len(heads), "#define PAT_NSTEP %d" % len(words), "#define PAT_PER_CAT 20", "",
         "typedef struct { uint16_t first; uint8_t len; uint8_t flags; } PatHead;     /* flags: bit0 DEG, bit1 F (idiom) */",
         '_Static_assert(sizeof(PatHead) == 4, "PatHead");', "",
         "static const PatHead PAT_HEAD[PAT_N] = {"]
    for i in range(0, len(heads), 4):
        L.append("    " + " ".join("{ %d, %d, %d }," % h for h in heads[i:i + 4]))
    L += ["};", "", "static const uint16_t PAT_STEP[PAT_NSTEP] = {"]
    for i in range(0, len(words), 12):
        L.append("    " + " ".join("0x%04X," % w for w in words[i:i + 12]))
    L += ["};", "", "#endif /* PATTERNS_DATA_H */", ""]
    return "\n".join(L)


def main():
    t = text()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != t:
            print("gen_patterns: patterns_data.h is stale (run python3 tests/design/gen_patterns.py)")
            return 1
        print("gen_patterns: patterns_data.h is current")
        return 0
    open(OUT, "w").write(t)
    print("wrote", os.path.relpath(OUT, pp.ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
