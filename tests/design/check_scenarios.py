"""Check the scenario files and write docs/design/scenarios/COVERAGE.md (P2-007).

  python3 tests/design/check_scenarios.py          check only; exit 1 on any failure
  python3 tests/design/check_scenarios.py --write  check, then rewrite COVERAGE.md

A step row is a markdown table row whose first cell is an integer and which has exactly 5 cells:
step | user action | exact screen text | MIDI out | row ids.  Row ids are `CONTROL/CONTEXT` (the control and context
columns of docs/design/control_map.tsv), comma separated; `*` is a wildcard (`KEY_W*/SCALE`); `-` means no control
(power-on, a host action).  The check fails on an unknown id, an empty cell, a step with the words TBD / choose / e.g.,
and on any control-map row that no scenario cites (those are listed as gaps in COVERAGE.md).
"""
import csv, fnmatch, glob, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
D = os.path.join(ROOT, "docs", "design")
SC = os.path.join(D, "scenarios")
BANNED = re.compile(r"TBD|choose|e\.g\.")
NARR = lambda sid: int(sid[1:]) <= 8 or int(sid[1:]) >= 18   # S01-S08 and S18 onward (S18 HARMONY, S19 ARP, ...) are hand-written walks; S09-S17 are generated sweeps
CTX = ["PERF", "NOTE_EDIT", "CHAN", "SET", "SCALE", "REC", "RESET", "HELP", "MENU"]


def load_rows():
    with open(os.path.join(D, "control_map.tsv"), newline="") as f:
        return [(r["control"], r["context"]) for r in csv.DictReader(f, delimiter="\t")]


def scenario_files():
    return sorted(glob.glob(os.path.join(SC, "S[0-9][0-9]-*.md")))


def parse(path):
    steps, errs = [], []
    for ln, line in enumerate(open(path, encoding="utf-8"), 1):
        if not re.match(r"\|\s*\d+\s*\|", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
        if len(cells) != 5:
            errs.append("%s:%d: %d cells, need 5" % (os.path.basename(path), ln, len(cells)))
            continue
        if any(not c for c in cells):
            errs.append("%s:%d: empty cell" % (os.path.basename(path), ln))
        steps.append((ln, cells))
    return steps, errs


def main():
    write = "--write" in sys.argv
    rows = load_rows()
    valid = set(rows)
    errs, cites = [], {}   # (control, ctx) -> set of scenario ids
    files = scenario_files()
    for p in files:
        sid = os.path.basename(p).split("-")[0]
        steps, e = parse(p)
        errs += e
        for ln, cells in steps:
            if BANNED.search(" ".join(cells)):
                errs.append("%s:%d: banned word in a step" % (os.path.basename(p), ln))
            for tok in [t.strip().strip("`") for t in cells[4].split(",")]:
                if tok in ("-", ""):
                    continue
                if "/" not in tok:
                    errs.append("%s:%d: bad row id %r" % (os.path.basename(p), ln, tok))
                    continue
                hit = [r for r in valid if fnmatch.fnmatchcase(r[0] + "/" + r[1], tok)]
                if not hit:
                    errs.append("%s:%d: unknown row id %r" % (os.path.basename(p), ln, tok))
                for r in hit:
                    cites.setdefault(r, set()).add(sid)
    for p in files + [os.path.join(SC, "COVERAGE.md")]:
        if os.path.exists(p) and BANNED.search(open(p, encoding="utf-8").read()):
            errs.append("%s: banned word" % os.path.basename(p))
    gaps = [r for r in rows if r not in cites]
    narrative = [r for r in rows if not any(NARR(s) for s in cites.get(r, ()))]
    print("scenarios: %d files, %d control-map rows, %d with no scenario, %d only in a sweep" %
          (len(files), len(rows), len(gaps), len(narrative)))
    for e in errs:
        print("FAIL", e)
    for g in gaps:
        print("GAP", "%s/%s" % g)
    if write:
        controls = []
        for c, _ in rows:
            if c not in controls:
                controls.append(c)
        L = ["# COVERAGE: which scenario exercises which control-map row (P2-007)", "",
             "Generated by `python3 tests/design/check_scenarios.py --write`; do not edit by hand. A row id is `CONTROL/CONTEXT` "
             "from `control_map.tsv` (%d controls x %d contexts = %d rows)." % (len(controls), len(CTX), len(rows)), "",
             "- S01 to S08 and S18 onward (S18 HARMONY P2-012, S19 ARP P2-013, later design scenarios) are the narrative scenarios (workflows). S09 to S17 are generated sweeps, one per page context, that walk "
             "every control once on that page; S09 = PERF, S10 = NOTE_EDIT, S11 = CHAN, S12 = SET, S13 = SCALE, S14 = REC, "
             "S15 = RESET, S16 = HELP, S17 = MENU.",
             "- Rows with no scenario at all (gaps, to be sent back to P2-001): **%d**." % len(gaps),
             "- Rows exercised only by a sweep and by no narrative scenario: **%d** of %d (listed in section 3)." % (len(narrative), len(rows)),
             "", "## 1. Gaps (no scenario cites the row)", ""]
        L += ["- `%s/%s`" % g for g in gaps] or ["None."]
        L += ["", "## 2. Matrix of narrative scenarios (S01 to S08, S18 onward) per row; `sw` = covered by the sweep of that page only", "",
              "| Control | " + " | ".join(CTX) + " |", "| --- |" + " --- |" * len(CTX)]
        for c in controls:
            cells = []
            for x in CTX:
                s = sorted(t for t in cites.get((c, x), ()) if NARR(t))
                cells.append(",".join(s) if s else ("sw" if (c, x) in cites else "GAP"))
            L.append("| `%s` | " % c + " | ".join(cells) + " |")
        L += ["", "## 3. Rows walked by a sweep and by no narrative scenario", ""]
        L += ["- `%s/%s`" % r for r in narrative]
        L.append("")
        open(os.path.join(SC, "COVERAGE.md"), "w", encoding="utf-8").write("\n".join(L))
        print("wrote", os.path.relpath(os.path.join(SC, "COVERAGE.md"), ROOT))
    return 1 if errs or gaps else 0


if __name__ == "__main__":
    sys.exit(main())
