"""The 1-bpp icons of screen v2 (P4-026, SCREEN_SPEC_V2 4.5): the art of docs/design/ui_review/proposals/v12/icons_v12.py.

  gen_sq_icons.py OUT.h            the firmware table (build/gen/ui_sqicons.h)
  gen_sq_icons.py --ref OUT.txt    the art as text for tests/ui_sq_test.c: `name w h` then h rows of # and .

An icon is w x h (w <= 16) with one uint16 per row, bit (w-1-x) = pixel x. The icons_v12 module imports `el` (the mock
tool's element library, which needs Pillow and fonts); only its IC table is wanted, so it is read with ast and
injected as the `el` module instead of importing the library.
"""
import ast
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
V12 = ROOT / "docs/design/ui_review/proposals/v12"
EL = ROOT / "docs/design/ui_review/proposals/v5/el.py"


def load():
    tree = ast.parse(EL.read_text())
    ic = None
    for n in tree.body:
        if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "IC" for t in n.targets):
            ic = ast.literal_eval(n.value)
    assert ic is not None, "el.py has no IC table"
    m = types.ModuleType("el")
    m.IC = ic
    sys.modules["el"] = m
    sys.path.insert(0, str(V12))
    import icons_v12                    # noqa: E402
    return icons_v12.ICONS


def rows_of(art):
    rows = art.strip("\n").split("\n")
    w = max(map(len, rows))
    assert w <= 16, "icon wider than 16"
    return w, [r.ljust(w, ".") for r in rows]


def main():
    icons = load()
    if len(sys.argv) == 3 and sys.argv[1] == "--ref":
        out = []
        for name, art in icons.items():
            w, rows = rows_of(art)
            out.append(f"{name} {w} {len(rows)}")
            out += [r.replace(" ", ".") for r in rows]
        Path(sys.argv[2]).write_text("\n".join(out) + "\n")
        return
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    names, tab, data = [], [], []
    for name, art in icons.items():
        w, rows = rows_of(art)
        tab.append((len(data), w, len(rows)))
        data += [sum(1 << (w - 1 - x) for x, c in enumerate(r) if c == "#") for r in rows]
        names.append(name)
    out = ["/* generated by tools/gen_sq_icons.py from docs/design/ui_review/proposals/v12/icons_v12.py: the 1-bpp icons of screen v2 */",
           "#pragma once", "#include <stdint.h>", "",
           "typedef struct { uint16_t off; uint8_t w, h; } sqicon_t;   /* rows SQI_ROWS[off .. off+h-1], bit (w-1-x) = pixel x */",
           "enum {"]
    out += [f"    SQI_{n.upper()}," for n in names] + ["    SQI_N", "};",
                f"static const uint16_t SQI_ROWS[{len(data)}] = {{"]
    for i in range(0, len(data), 13):
        out.append("    " + ", ".join(f"0x{v:04x}" for v in data[i:i + 13]) + ",")
    out += ["};", "static const sqicon_t SQI_TAB[SQI_N] = {"]
    out += [f"    {{{o}, {w}, {h}}},   /* {n} */" for (o, w, h), n in zip(tab, names)] + ["};", ""]
    Path(sys.argv[1]).write_text("\n".join(out))


if __name__ == "__main__":
    main()
